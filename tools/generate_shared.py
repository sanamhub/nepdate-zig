#!/usr/bin/env python3
"""Generate src/generated/shared_data.zig from the vendored shared data.

    python tools/generate_shared.py
    python tools/generate_shared.py --check

The Zig port gets the calendar and patro tables from the C amalgamation, not
from Zig arrays. This generator still checks the shared data and records the
bounds and counts the Zig side uses (the constants are compiled, not read from
JSON at runtime).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"
OUT = ROOT / "src" / "generated" / "shared_data.zig"


def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    raise SystemExit(1)


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def patro_counts(years: list[int]) -> dict[str, int]:
    days = tithi_days = holidays = event_days = events = 0
    names: set[tuple[str, str]] = set()
    for year in years:
        data = load(SHARED / "data" / "patro" / f"{year}.json")
        if data.get("schema") != 1 or data.get("year") != year:
            fail(f"data/patro/{year}.json has an unexpected schema or year")
        for day, value in data.get("days", {}).items():
            days += 1
            if "tithi" in value:
                tithi_days += 1
                names.add((value["tithi"]["np"], value["tithi"]["en"]))
            if value.get("holiday"):
                holidays += 1
            day_events = value.get("events", [])
            if day_events:
                event_days += 1
            events += len(day_events)
            for event in day_events:
                names.add((event["np"], event["en"]))
    return {
        "days": days,
        "tithi_days": tithi_days,
        "holidays": holidays,
        "event_days": event_days,
        "events": events,
        "names": len(names),
        "name_bytes": sum(len(np.encode()) + len(en.encode()) for np, en in names),
    }


def build() -> str:
    calendar = load(SHARED / "data" / "calendar" / "bs-calendar.json")
    summary = load(SHARED / "spec" / "vectors" / "patro-summary.json")
    if calendar.get("schema") != 1:
        fail("calendar/bs-calendar.json has an unexpected schema")
    years = sorted(int(year) for year in calendar["month_lengths"])
    if years != list(range(calendar["min_year"], calendar["max_year"] + 1)):
        fail("calendar month lengths do not cover every supported year")
    lengths = [len(calendar["month_lengths"][str(year)]) for year in years]
    if any(length != 12 for length in lengths):
        fail("a calendar year does not have twelve months")
    total_days = sum(sum(calendar["month_lengths"][str(year)]) for year in years)
    counts = patro_counts(list(range(summary["first_year"], summary["last_year"] + 1)))
    coverage_days = summary["last_serial"] - summary["first_serial"] + 1
    if coverage_days != summary["days"]:
        fail(f"patro coverage is {coverage_days} days, summary says {summary['days']}")
    for key in ("tithi_days", "holidays", "event_days", "events", "names", "name_bytes"):
        if counts[key] != summary[key]:
            fail(f"patro {key} is {counts[key]}, summary says {summary[key]}")
        if counts[key] != summary[key]:
            fail(f"patro {key} is {counts[key]}, summary says {summary[key]}")

    return f"""//! Generated by tools/generate_shared.py from shared/data and shared/spec.
//! Do not edit. Run the generator after a shared/ sync; --check verifies it.

pub const min_year: i32 = {calendar["min_year"]};
pub const max_year: i32 = {calendar["max_year"]};
pub const min_serial: i32 = 0;
pub const max_serial: i32 = {total_days - 1};
pub const total_days: i32 = {total_days};

pub const patro_first_year: i32 = {summary["first_year"]};
pub const patro_last_year: i32 = {summary["last_year"]};
pub const patro_first_serial: i32 = {summary["first_serial"]};
pub const patro_last_serial: i32 = {summary["last_serial"]};
pub const patro_days: i32 = {summary["days"]};
pub const tithi_days: i32 = {summary["tithi_days"]};
pub const holidays: i32 = {summary["holidays"]};
pub const event_days: i32 = {summary["event_days"]};
pub const events: i32 = {summary["events"]};
pub const names: i32 = {summary["names"]};
pub const name_bytes: i32 = {summary["name_bytes"]};
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.exists():
            fail(f"{OUT.relative_to(ROOT)} is missing; run python tools/generate_shared.py")
        if OUT.read_text(encoding="utf-8") != text:
            fail(f"{OUT.relative_to(ROOT)} is stale; run python tools/generate_shared.py")
        print(f"shared data OK: {OUT.relative_to(ROOT)}")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
